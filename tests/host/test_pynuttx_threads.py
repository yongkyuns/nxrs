"""Host controls for the pinned debugger patch; real GDB/QEMU is a separate gate.

Execute the original and patched helper definitions against literal native
mutex/context evidence. No target function or copied helper implementation is
used as the oracle. NXRS_NUTTX_TEST_SOURCE may name a read-only pinned checkout.
"""

import ast
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
from types import SimpleNamespace
import unittest


ROOT = Path(__file__).resolve().parents[2]
NUTTX = Path(os.environ.get("NXRS_NUTTX_TEST_SOURCE", ROOT / "external/nuttx"))
PATCH = ROOT / "upstream/nuttx/patches/0151-pynuttx-task-context-and-mutex-owners.patch"


def definitions(path, names, namespace):
    tree = ast.parse(path.read_text(), filename=str(path))
    tree.body = [node for node in tree.body
                 if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name in names]
    exec(compile(tree, str(path), "exec"), namespace)
    return namespace


class NativePointer(dict):
    def cast(self, _):
        return self


class LazyRegister:
    def __init__(self, target, name):
        self.target, self.name = target, name

    def __int__(self):
        return self.target.registers[self.name]


class Frame:
    def __init__(self, target, level):
        self.target, self.depth = target, level

    def level(self):
        return self.depth

    def select(self):
        self.target.selected = self.depth

    def older(self):
        return Frame(self.target, self.depth + 1)

    def read_register(self, name):
        if self.depth:
            raise AssertionError("Register snapshot must use the live frame")
        return LazyRegister(self.target, name) if self.target.lazy else self.target.registers[name]


class Target:
    """Small stopped-target double: literal registers, task states and contexts."""
    COMMAND_USER = 0
    GdbError = RuntimeError
    error = RuntimeError

    class Command:
        def __init__(self, *args):
            pass

    def __init__(self, *, xtensa=False, lazy=False):
        self.xtensa, self.lazy, self.selected = xtensa, lazy, 0
        self.registers = {"pc": 0x1000, "sp": 0x9000}
        if xtensa:
            self.registers = {"pc": 0x1000, "ps": 0x40000, "windowbase": 11,
                              "windowstart": 0x888, **{f"ar{i}": 0x9000 + i for i in range(64)}}
        self.original = self.registers.copy()
        self.contexts = {0x5000: {"pc": 0x2000, "sp": 0xA000},
                         0x6000: {"pc": 0x3000, "sp": 0xB000}}
        self.tasks = [NativePointer(pid=4, task_state=3, xcp={"regs": 0x6000},
                                    name=SimpleNamespace(string=lambda: "running")),
                      NativePointer(pid=5, task_state=5, xcp={"regs": 0x5000},
                                    name=SimpleNamespace(string=lambda: "blocked"))]
        self.observed = []
        self.writes = []
        self.thread = SimpleNamespace(switch=self.switch)
        self.output = []

    def switch(self):
        self.selected = 0

    def newest_frame(self):
        return Frame(self, 0)

    def selected_frame(self):
        return Frame(self, self.selected)

    def selected_thread(self):
        return self.thread

    def write(self, value):
        self.output.append(value)

    def lookup_type(self, _):
        return SimpleNamespace(pointer=lambda: None)

    def parse_and_eval(self, name):
        return {"g_npidhash": len(self.tasks), "g_pidhash": self.tasks}[name]

    def load(self, address):
        # A target context is independent literal data, not generated by the
        # helper. This hook isolates save/restore from GDB's target-memory API.
        if self.xtensa:
            self.registers.update(pc=0x2000, ps=0x40010, windowstart=1 << 11)
            for i in range(16):
                self.registers[f"ar{(44+i) % 64}"] = 0xA000 + i
        else:
            self.registers.update(self.contexts[int(address)])

    def execute(self, command, **_):
        command = command.strip()
        match = re.fullmatch(r"set \$(\w+)=(\d+)", command)
        if match:
            if self.selected:
                raise AssertionError("Register write targeted an unwound frame")
            self.writes.append(match[1])
            self.registers[match[1]] = int(match[2])
        elif command.startswith("setregs "):
            slot = int(re.search(r"\[(\d+)\]", command)[1])
            self.helper.save()
            self.load(self.tasks[slot]["xcp"]["regs"])
        elif command == "fail":
            raise RuntimeError("deliberate inspection error")
        elif command == "inspect":
            self.observed.append(self.registers.copy())
        else:
            raise AssertionError(f"Unexpected GDB command: {command}")
        return ""


def load_thread(source, target):
    utils = SimpleNamespace(
        is_target_arch=lambda name: target.xtensa and name == "xtensa",
        ArrayIterator=lambda values, count: iter(values[:count]),
        get_symbol_value=lambda name: None,
        lookup_type=target.lookup_type,
    )
    namespace = dict(gdb=target, utils=utils, re=re, SEM_TYPE_MUTEX=4,
                     NXSEM_MBLOCKING_BIT=0x80000000, NXSEM_NO_MHOLDER=0x7FFFFFFE,
                     TSTATE_TASK_RUNNING=3)
    definitions(source / "thread.py", {"Registers", "Nxthread", "DeadLock", "Ps", "mutex_holder"}, namespace)
    registers = namespace["Registers"]
    registers.reginfo = ({"pc": {}, "ps": {}, **{f"a{i}": {} for i in range(16)}}
                         if target.xtensa else {"pc": {}, "sp": {}})
    helper = registers()
    helper.load = target.load
    target.helper = namespace["g_registers"] = helper
    return namespace


class ThreadHelperTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls.temp.cleanup)
        cls.before = NUTTX / "tools/pynuttx/nxgdb"
        cls.tree = Path(cls.temp.name)
        cls.after = cls.tree / "tools/pynuttx/nxgdb"
        cls.after.mkdir(parents=True)
        for name in ("thread.py", "utils.py"):
            shutil.copy2(cls.before / name, cls.after / name)
        subprocess.run(["git", "apply", str(PATCH)], cwd=cls.tree, check=True,
                       env={**os.environ, "GIT_CEILING_DIRECTORIES": str(cls.tree.parent)},
                       capture_output=True, text=True)

    def test_current_native_owner_cycle_and_healthy_wait(self):
        for source, patched in ((self.before, False), (self.after, True)):
            with self.subTest(patched=patched):
                target = Target()
                ns = load_thread(source, target)
                mutex_a = NativePointer(flags=5, sem={"val": {"mholder": 0x80000005}})
                mutex_b = NativePointer(flags=5, sem={"val": {"mholder": 0x80000006}})
                tasks = {5: NativePointer(pid=5, waitobj=mutex_b),
                         6: NativePointer(pid=6, waitobj=mutex_a),
                         4: NativePointer(pid=4, waitobj=None)}
                ns["utils"].get_tcb = tasks.get
                detector = ns["DeadLock"]()
                if not patched:
                    with self.assertRaises(KeyError):
                        detector.collect([tasks[5], tasks[6]])
                    continue
                self.assertEqual(detector.collect([tasks[5], tasks[6]]), [(5, [6, 5])])
                mutex_b["sem"]["val"]["mholder"] = 0x80000004
                self.assertEqual(detector.collect([tasks[5], tasks[4]]), [])
                for encoded in (0x7FFFFFFE, 0xFFFFFFFE, 0x7FFFFFFF, 0xFFFFFFFF):
                    mutex_b["sem"]["val"]["mholder"] = encoded
                    self.assertEqual(ns["mutex_holder"](mutex_b), -1)

    def test_error_restores_eager_register_values_and_selected_frame(self):
        old = Target()
        ns = load_thread(self.before, old)
        with self.assertRaisesRegex(RuntimeError, "deliberate"):
            ns["Nxthread"].__new__(ns["Nxthread"]).invoke("apply 1 fail", False)
        self.assertNotEqual(old.registers, old.original)

        for xtensa in (False, True):
            for selection in (0, 1):
                for command in ("apply 1 fail", "apply all fail"):
                    with self.subTest(xtensa=xtensa, selection=selection, command=command):
                        target = Target(xtensa=xtensa, lazy=True)
                        target.selected = selection
                        ns = load_thread(self.after, target)
                        with self.assertRaisesRegex(RuntimeError, "deliberate"):
                            ns["Nxthread"].__new__(ns["Nxthread"]).invoke(command, False)
                        self.assertEqual(target.registers, target.original)
                        self.assertEqual(target.selected, selection)
                        self.assertIsNone(ns["Registers"].saved_regs)

    def test_running_task_uses_live_context_instead_of_stale_saved_pointer(self):
        for source, expected_pc in ((self.before, 0x3000), (self.after, 0x1000)):
            target = Target()
            ns = load_thread(source, target)
            ns["Nxthread"].__new__(ns["Nxthread"]).invoke("apply all inspect", False)
            self.assertEqual(target.observed[0]["pc"], expected_pc)
            self.assertEqual(target.observed[1]["pc"], 0x2000)
            self.assertEqual(target.registers, target.original)

    def test_ps_missing_macro_information_is_an_explicit_prerequisite(self):
        for source, error, message in ((self.before, TypeError, "NoneType"),
                                       (self.after, RuntimeError, "native macro debug information.*-g3")):
            target = Target()
            ns = load_thread(source, target)
            with self.assertRaisesRegex(error, message):
                ns["Ps"]().invoke("", False)

    def test_xtensa_layout_uses_native_table_not_remote_packet_order(self):
        offsets = [0xFFFF] * 128
        offsets[:6] = [0, 4, 88, 92, 96, 72]
        offsets[64:80] = range(8, 72, 4)

        class OffsetTable(list):
            address = 0x4000
            type = SimpleNamespace(strip_typedefs=lambda: SimpleNamespace(range=lambda: (0, 127)))

        table = OffsetTable(offsets)
        target = SimpleNamespace(GdbError=RuntimeError, parse_and_eval=lambda name: {
            "g_tcbinfo": {"regs_num": 28, "reg_off": {"p": 0x4000}},
            "g_reg_offs": table,
        }[name])
        ns = definitions(self.after / "utils.py", {"get_register_layout"},
                         dict(gdb=target, re=re, is_target_arch=lambda name: name == "xtensa"))
        layout = ns["get_register_layout"]()
        self.assertEqual(layout["pc"]["tcb_reg_off"], 0)
        self.assertEqual(layout["ps"]["tcb_reg_off"], 4)
        self.assertEqual(layout["a1"]["tcb_reg_off"], 12)
        self.assertEqual(layout["a15"]["tcb_reg_off"], 68)
        self.assertNotIn("ar1", layout)
        table.address = 0x5000
        with self.assertRaisesRegex(RuntimeError, "offset table"):
            ns["get_register_layout"]()


if __name__ == "__main__":
    unittest.main()
