//! Deterministic, manually advanced sensor simulation shared by HAL providers.
#![no_std]
#![forbid(unsafe_code)]

// This engine is compiled only for the desktop simulation runtime.
extern crate std;

pub mod runtime;

use std::collections::{BTreeSet, VecDeque};
use std::sync::{Arc, Condvar, Mutex};

pub type TimeUs = u64;
pub const DEFAULT_IMU_PERIOD_US: TimeUs = 10_000;
pub const DEFAULT_GNSS_PERIOD_US: TimeUs = 200_000;

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub enum Source {
    Imu,
    Gnss,
}

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub struct EventKey {
    pub time_us: TimeUs,
    pub source: Source,
    pub sequence: u64,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ImuObservation {
    /// Acceleration in micro-g.
    pub accel_ug: [i32; 3],
    /// Angular velocity in micro-degrees per second.
    pub gyro_udps: [i32; 3],
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct GnssObservation {
    /// Latitude and longitude in degrees multiplied by 1e7.
    pub latitude_e7: i32,
    pub longitude_e7: i32,
    /// Altitude in millimetres.
    pub altitude_mm: i32,
    /// Ground speed in millimetres per second.
    pub speed_mm_s: u32,
    /// Course clockwise from north in milliradians.
    pub course_mrad: Option<u32>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Observation {
    Imu(ImuObservation),
    Gnss(GnssObservation),
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Event {
    pub key: EventKey,
    pub observation: Observation,
}

#[derive(Clone, Debug)]
pub struct SimulationSpec {
    pub seed: u64,
    pub sources: BTreeSet<Source>,
    pub imu_period_us: TimeUs,
    pub gnss_period_us: TimeUs,
    pub queue_capacity: usize,
    /// Maximum total events generated by a single `advance_to` call.
    pub max_events_per_advance: usize,
}

impl SimulationSpec {
    pub fn coordinated(seed: u64) -> Self {
        Self {
            seed,
            sources: [Source::Imu, Source::Gnss].into_iter().collect(),
            imu_period_us: DEFAULT_IMU_PERIOD_US,
            gnss_period_us: DEFAULT_GNSS_PERIOD_US,
            queue_capacity: 32,
            max_events_per_advance: 100_000,
        }
    }

    pub fn validate(&self) -> Result<(), Error> {
        if self.sources.is_empty()
            || self.imu_period_us == 0
            || self.gnss_period_us == 0
            || self.queue_capacity == 0
            || self.max_events_per_advance == 0
        {
            return Err(Error::InvalidSpec);
        }
        Ok(())
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Error {
    InvalidSpec,
    SourceNotConfigured,
    Busy,
    BarrierNotReady,
    TimeWentBackwards,
    AdvanceTooLarge,
    SequenceExhausted,
    Cancelled,
    EndpointsStillLeased,
}

#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct AdvanceReport {
    pub generated: usize,
    pub dropped: usize,
}

#[derive(Clone)]
pub struct Simulation {
    shared: Arc<Shared>,
}

struct Shared {
    spec: SimulationSpec,
    state: Mutex<State>,
    changed: Condvar,
}

struct State {
    now_us: TimeUs,
    active: BTreeSet<Source>,
    queues: [VecDeque<Event>; 2],
    canceled: [bool; 2],
    generation: [u64; 2],
    next_us: [Option<TimeUs>; 2],
    sequence: [u64; 2],
    started: bool,
    session_canceled: bool,
    dropped: [u64; 2],
}

impl Simulation {
    pub fn new(spec: SimulationSpec) -> Result<Self, Error> {
        spec.validate()?;
        Ok(Self {
            shared: Arc::new(Shared {
                spec,
                state: Mutex::new(State {
                    now_us: 0,
                    active: BTreeSet::new(),
                    queues: [VecDeque::new(), VecDeque::new()],
                    canceled: [false; 2],
                    generation: [0; 2],
                    next_us: [None, None],
                    sequence: [0, 0],
                    started: false,
                    session_canceled: false,
                    dropped: [0, 0],
                }),
                changed: Condvar::new(),
            }),
        })
    }

    pub fn lease(&self, source: Source) -> Result<EndpointLease, Error> {
        if !self.shared.spec.sources.contains(&source) {
            return Err(Error::SourceNotConfigured);
        }
        let mut state = self.shared.state.lock().unwrap();
        if !state.active.insert(source) {
            return Err(Error::Busy);
        }
        let index = source_index(source);
        state.generation[index] = state.generation[index].wrapping_add(1);
        let generation = state.generation[index];
        state.canceled[index] = false;
        state.queues[index].clear();
        state.next_us[index] = state.now_us.checked_add(period(&self.shared.spec, source));
        self.shared.changed.notify_all();
        Ok(EndpointLease {
            shared: self.shared.clone(),
            source,
            generation,
            released: false,
        })
    }

    /// Wait until every configured source has an owned lease for the initial start barrier.
    pub fn start(&self) -> Result<(), Error> {
        let mut state = self.shared.state.lock().unwrap();
        while !state.session_canceled
            && !self.shared.spec.sources.iter().all(|source| {
                state.active.contains(source) && !state.canceled[source_index(*source)]
            })
        {
            state = self.shared.changed.wait(state).unwrap();
        }
        if state.session_canceled {
            return Err(Error::Cancelled);
        }
        state.started = true;
        self.shared.changed.notify_all();
        Ok(())
    }

    /// Advance logical time. Calls exceeding the configured work bound are rejected atomically.
    pub fn advance_to(&self, target_us: TimeUs) -> Result<AdvanceReport, Error> {
        let mut state = self.shared.state.lock().unwrap();
        if !state.started {
            return Err(Error::BarrierNotReady);
        }
        if state.session_canceled {
            return Err(Error::Cancelled);
        }
        if target_us < state.now_us {
            return Err(Error::TimeWentBackwards);
        }
        let mut due = 0u128;
        for source in &self.shared.spec.sources {
            let i = source_index(*source);
            if let Some(next_us) =
                state.next_us[i].filter(|_| !state.canceled[i] && state.active.contains(source))
            {
                if next_us <= target_us {
                    let count =
                        u128::from((target_us - next_us) / period(&self.shared.spec, *source)) + 1;
                    due += count;
                    if count > u128::from(u64::MAX - state.sequence[i]) {
                        return Err(Error::SequenceExhausted);
                    }
                }
            }
        }
        if due > self.shared.spec.max_events_per_advance as u128 {
            return Err(Error::AdvanceTooLarge);
        }
        let mut report = AdvanceReport::default();
        loop {
            let next = self
                .shared
                .spec
                .sources
                .iter()
                .filter_map(|source| {
                    let i = source_index(*source);
                    if state.canceled[i] || !state.active.contains(source) {
                        return None;
                    }
                    state.next_us[i].map(|time_us| EventKey {
                        time_us,
                        source: *source,
                        sequence: state.sequence[i],
                    })
                })
                .filter(|key| key.time_us <= target_us)
                .min();
            let Some(key) = next else { break };
            let i = source_index(key.source);
            state.sequence[i] += 1;
            state.next_us[i] = key
                .time_us
                .checked_add(period(&self.shared.spec, key.source));
            let event = Event {
                key,
                observation: project(self.shared.spec.seed, key.source, key.time_us),
            };
            let full = state.queues[i].len() == self.shared.spec.queue_capacity;
            if full {
                state.queues[i].pop_front();
                state.dropped[i] += 1;
                report.dropped += 1;
            }
            state.queues[i].push_back(event);
            report.generated += 1;
        }
        state.now_us = target_us;
        self.shared.changed.notify_all();
        Ok(report)
    }

    pub fn cancel(&self) {
        let mut state = self.shared.state.lock().unwrap();
        state.session_canceled = true;
        self.shared.changed.notify_all();
    }

    /// Clear scenario state only after all endpoint owners have dropped their leases.
    pub fn reset_after_join(&self) -> Result<(), Error> {
        let mut state = self.shared.state.lock().unwrap();
        if !state.active.is_empty() {
            return Err(Error::EndpointsStillLeased);
        }
        *state = State {
            now_us: 0,
            active: BTreeSet::new(),
            queues: [VecDeque::new(), VecDeque::new()],
            canceled: [false; 2],
            generation: [0; 2],
            next_us: [None, None],
            sequence: [0, 0],
            started: false,
            session_canceled: false,
            dropped: [0, 0],
        };
        self.shared.changed.notify_all();
        Ok(())
    }

    pub fn now_us(&self) -> TimeUs {
        self.shared.state.lock().unwrap().now_us
    }
}

pub struct EndpointLease {
    shared: Arc<Shared>,
    source: Source,
    generation: u64,
    released: bool,
}

impl EndpointLease {
    pub fn source(&self) -> Source {
        self.source
    }

    /// Clonable stop handle for waking a task without releasing its owned lease.
    pub fn cancel_handle(&self) -> CancelHandle {
        CancelHandle {
            shared: self.shared.clone(),
            source: self.source,
            generation: self.generation,
        }
    }

    pub fn try_recv(&self) -> Result<Option<Event>, Error> {
        let mut state = self.shared.state.lock().unwrap();
        let i = source_index(self.source);
        if state.canceled[i] || state.session_canceled {
            return Err(Error::Cancelled);
        }
        Ok(state.queues[i].pop_front())
    }

    pub fn recv(&self) -> Result<Event, Error> {
        let mut state = self.shared.state.lock().unwrap();
        let i = source_index(self.source);
        loop {
            if state.canceled[i] || state.session_canceled {
                return Err(Error::Cancelled);
            }
            if let Some(event) = state.queues[i].pop_front() {
                return Ok(event);
            }
            state = self.shared.changed.wait(state).unwrap();
        }
    }

    pub fn dropped(&self) -> u64 {
        self.shared.state.lock().unwrap().dropped[source_index(self.source)]
    }

    fn release(&mut self) {
        if !self.released {
            let mut state = self.shared.state.lock().unwrap();
            state.active.remove(&self.source);
            state.queues[source_index(self.source)].clear();
            self.shared.changed.notify_all();
            self.released = true;
        }
    }
}

impl Drop for EndpointLease {
    fn drop(&mut self) {
        self.release();
    }
}

#[derive(Clone)]
pub struct CancelHandle {
    shared: Arc<Shared>,
    source: Source,
    generation: u64,
}

impl CancelHandle {
    pub fn cancel(&self) {
        let mut state = self.shared.state.lock().unwrap();
        let index = source_index(self.source);
        if state.active.contains(&self.source) && state.generation[index] == self.generation {
            state.canceled[index] = true;
            self.shared.changed.notify_all();
        }
    }
}

fn source_index(source: Source) -> usize {
    match source {
        Source::Imu => 0,
        Source::Gnss => 1,
    }
}
fn period(spec: &SimulationSpec, source: Source) -> TimeUs {
    match source {
        Source::Imu => spec.imu_period_us,
        Source::Gnss => spec.gnss_period_us,
    }
}

fn project(seed: u64, source: Source, time_us: TimeUs) -> Observation {
    const PHASE_US: u64 = 4_000_000;
    let time = time_us % (4 * PHASE_US);
    let within = (time % PHASE_US) as i64;
    let mixed = mix64(seed);
    let magnitude = 125 + (mixed % 126) as i64;
    // A level east-west shuttle. Position and velocity are continuous at
    // phase boundaries; acceleration changes direction every half traverse.
    let (start_mm, start_mm_s, accel_mm_s2) = match time / PHASE_US {
        0 => (0, 0, magnitude),
        1 => (8 * magnitude, 4 * magnitude, -magnitude),
        2 => (16 * magnitude, 0, -magnitude),
        _ => (8 * magnitude, -4 * magnitude, magnitude),
    };
    match source {
        Source::Imu => Observation::Imu(ImuObservation {
            accel_ug: [(accel_mm_s2 * 100_000_000 / 980_665) as i32, 0, 1_000_000],
            gyro_udps: [0; 3],
        }),
        Source::Gnss => {
            let east_mm = start_mm
                + start_mm_s * within / 1_000_000
                + accel_mm_s2 * within * within / 2_000_000_000_000;
            let east_mm_s = start_mm_s + accel_mm_s2 * within / 1_000_000;
            let latitude_e7 = 450_000_000 + (mixed as i32 % 1_000_000);
            let longitude_e7 = -730_000_000
                + ((mixed >> 32) as i32 % 1_000_000)
                + (east_mm * 1_000 / 7_885) as i32;
            Observation::Gnss(GnssObservation {
                latitude_e7,
                longitude_e7,
                altitude_mm: 12_000,
                speed_mm_s: east_mm_s.unsigned_abs() as u32,
                course_mrad: match east_mm_s.cmp(&0) {
                    core::cmp::Ordering::Greater => Some(1_571),
                    core::cmp::Ordering::Less => Some(4_712),
                    core::cmp::Ordering::Equal => None,
                },
            })
        }
    }
}

fn mix64(mut value: u64) -> u64 {
    value = value.wrapping_add(0x9e37_79b9_7f4a_7c15);
    value = (value ^ (value >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    value = (value ^ (value >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    value ^ (value >> 31)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::thread;
    use std::vec::Vec;

    fn spec(seed: u64, capacity: usize) -> SimulationSpec {
        let mut spec = SimulationSpec::coordinated(seed);
        spec.queue_capacity = capacity;
        spec
    }

    fn start_pair(sim: &Simulation) -> (EndpointLease, EndpointLease) {
        let imu = sim.lease(Source::Imu).unwrap();
        let gnss = sim.lease(Source::Gnss).unwrap();
        sim.start().unwrap();
        (imu, gnss)
    }

    fn schedule(seed: u64, advances: &[u64]) -> Vec<Event> {
        let sim = Simulation::new(spec(seed, 512)).unwrap();
        let (imu, gnss) = start_pair(&sim);
        for &time_us in advances {
            sim.advance_to(time_us).unwrap();
        }
        let mut events = Vec::new();
        while let Some(event) = imu.try_recv().unwrap() {
            events.push(event);
        }
        while let Some(event) = gnss.try_recv().unwrap() {
            events.push(event);
        }
        events.sort_by_key(|event| event.key);
        events
    }

    #[test]
    fn repeated_schedules_are_seeded_and_stably_ordered() {
        let first = schedule(17, &[1_000_000]);
        assert_eq!(first, schedule(17, &[37_000, 205_000, 1_000_000]));
        assert_ne!(first, schedule(18, &[1_000_000]));
        assert!(first.windows(2).all(|pair| pair[0].key < pair[1].key));
    }

    #[test]
    fn imu_and_gnss_project_the_same_eastward_acceleration() {
        let events = schedule(17, &[400_000]);
        let at = |source, time_us| {
            events
                .iter()
                .find(|event| event.key.source == source && event.key.time_us == time_us)
                .unwrap()
                .observation
        };
        let Observation::Imu(imu) = at(Source::Imu, 400_000) else {
            panic!("IMU observation")
        };
        let Observation::Gnss(first) = at(Source::Gnss, 200_000) else {
            panic!("GNSS observation")
        };
        let Observation::Gnss(second) = at(Source::Gnss, 400_000) else {
            panic!("GNSS observation")
        };
        let predicted_change_mm_s = f64::from(imu.accel_ug[0]) * 9.80665 * 0.2 / 1_000.0;
        let change_mm_s = f64::from(second.speed_mm_s - first.speed_mm_s);
        assert!((predicted_change_mm_s - change_mm_s).abs() < 1.0);
        assert!(second.longitude_e7 > first.longitude_e7);
        assert_eq!(second.latitude_e7, first.latitude_e7);
        assert_eq!(second.course_mrad, Some(1_571));
    }

    #[test]
    fn bounded_queues_drop_oldest_and_large_advances_are_atomic() {
        let mut cfg = spec(4, 2);
        cfg.max_events_per_advance = 3;
        let sim = Simulation::new(cfg).unwrap();
        let (imu, _gnss) = start_pair(&sim);
        assert_eq!(sim.advance_to(40_000), Err(Error::AdvanceTooLarge));
        assert_eq!(sim.now_us(), 0);
        let report = sim.advance_to(30_000).unwrap();
        assert_eq!(report.generated, 3);
        assert_eq!(report.dropped, 1);
        assert_eq!(imu.dropped(), 1);
        assert_eq!(imu.try_recv().unwrap().unwrap().key.sequence, 1);
        assert_eq!(imu.try_recv().unwrap().unwrap().key.sequence, 2);
    }

    #[test]
    fn maximum_logical_time_emits_final_tick_without_overflow_or_replay() {
        let mut cfg = spec(8, 2);
        cfg.sources = [Source::Imu].into_iter().collect();
        cfg.imu_period_us = TimeUs::MAX;
        let sim = Simulation::new(cfg).unwrap();
        let imu = sim.lease(Source::Imu).unwrap();
        sim.start().unwrap();
        assert_eq!(sim.advance_to(TimeUs::MAX).unwrap().generated, 1);
        assert_eq!(imu.try_recv().unwrap().unwrap().key.time_us, TimeUs::MAX);
        assert_eq!(sim.advance_to(TimeUs::MAX).unwrap().generated, 0);
    }

    #[test]
    fn endpoint_cancel_wakes_its_waiter_without_stopping_other_source() {
        let sim = Simulation::new(spec(5, 4)).unwrap();
        let (imu, gnss) = start_pair(&sim);
        let cancel = imu.cancel_handle();
        let waiter = thread::spawn(move || imu.recv());
        cancel.cancel();
        assert_eq!(waiter.join().unwrap(), Err(Error::Cancelled));
        assert_eq!(sim.advance_to(DEFAULT_GNSS_PERIOD_US).unwrap().generated, 1);
        assert!(gnss.try_recv().unwrap().is_some());
    }

    #[test]
    fn detach_rejoin_and_reset_require_joined_owners() {
        let sim = Simulation::new(spec(6, 8)).unwrap();
        let (imu, gnss) = start_pair(&sim);
        assert_eq!(sim.lease(Source::Imu).err(), Some(Error::Busy));
        sim.advance_to(DEFAULT_IMU_PERIOD_US).unwrap();
        drop(imu);
        assert_eq!(sim.reset_after_join(), Err(Error::EndpointsStillLeased));
        let imu = sim.lease(Source::Imu).unwrap();
        let stale_cancel = gnss.cancel_handle();
        drop(gnss);
        let gnss = sim.lease(Source::Gnss).unwrap();
        stale_cancel.cancel();
        sim.advance_to(DEFAULT_GNSS_PERIOD_US + DEFAULT_IMU_PERIOD_US)
            .unwrap();
        assert!(matches!(
            gnss.try_recv().unwrap(),
            Some(Event {
                key: EventKey {
                    source: Source::Gnss,
                    ..
                },
                ..
            })
        ));
        assert!(imu.try_recv().unwrap().is_some());
        drop(imu);
        drop(gnss);
        sim.reset_after_join().unwrap();
        let (imu, gnss) = start_pair(&sim);
        sim.advance_to(DEFAULT_IMU_PERIOD_US).unwrap();
        assert_eq!(imu.try_recv().unwrap().unwrap().key.sequence, 0);
        assert_eq!(gnss.try_recv().unwrap(), None);
    }

    #[test]
    fn independent_sessions_do_not_share_scenario_state() {
        let a = Simulation::new(spec(19, 8)).unwrap();
        let b = Simulation::new(spec(19, 8)).unwrap();
        let (a_imu, a_gnss) = start_pair(&a);
        let (b_imu, b_gnss) = start_pair(&b);
        a.advance_to(DEFAULT_IMU_PERIOD_US).unwrap();
        assert_eq!(a_imu.try_recv().unwrap().unwrap().key.sequence, 0);
        assert_eq!(b_imu.try_recv().unwrap(), None);
        assert_eq!(a.now_us(), DEFAULT_IMU_PERIOD_US);
        assert_eq!(b.now_us(), 0);
        drop((a_imu, a_gnss, b_imu, b_gnss));
    }
}
