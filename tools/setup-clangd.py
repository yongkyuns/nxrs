#!/usr/bin/env python3
"""Generate local clangd settings for native bridges and optional target builds."""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def output(command):
    return subprocess.check_output(command, text=True).strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--compile-commands", type=Path,
        help="merge a real build database; entries must refer to this checkout's sources",
    )
    args = parser.parse_args()
    entries = []
    if args.compile_commands:
        entries = json.loads(args.compile_commands.read_text())
        # Resolve relative directories against the database location, never the
        # editor's working directory. Preserve each build's actual flags.
        for entry in entries:
            directory = Path(entry["directory"])
            if not directory.is_absolute():
                directory = args.compile_commands.resolve().parent / directory
            entry["directory"] = str(directory.resolve())
            entry["file"] = str((directory / entry["file"]).resolve())

    configured = {entry["file"] for entry in entries}
    if sys.platform == "darwin":
        compiler = output(["xcrun", "--sdk", "macosx", "--find", "clang"])
        sdk = output(["xcrun", "--sdk", "macosx", "--show-sdk-path"])
        for source in sorted(ROOT.glob("hal/*/src/platform/macos/ffi/*")):
            if source.suffix not in {".c", ".m"} or str(source) in configured:
                continue
            flags = [compiler, "-isysroot", sdk, "-Wall", "-Wextra"]
            if source.suffix == ".m":
                flags.append("-fobjc-arc")
            flags += ["-I", str(source.parent)]
            entries.append({
                "directory": str(ROOT), "file": str(source),
                "arguments": [*flags, "-c", str(source)],
            })

    # Config is JSON (valid YAML), avoiding an additional YAML dependency.
    # Suppress only unavailable platform sources, retaining diagnostics for
    # native bridges, portable fixtures, and explicitly configured target files.
    configured_paths = [
        re.escape(str(Path(entry["file"]).relative_to(ROOT)))
        for entry in entries if Path(entry["file"]).is_relative_to(ROOT)
    ]
    foreign = [
        r"hal/[^/]+/src/platform/nuttx/.*", r"platform/nuttx/.*",
        r"tests/nuttx/.*", r"tests/nuttx-std/.*",
        r"external/(nuttx|nuttx-apps|apps)/.*",
        r"tests/event-services-comparison/.*(nuttx|zephyr).*",
    ]
    if sys.platform != "linux":
        foreign += [r"hal/[^/]+/src/platform/linux/.*", r"tests/host/linux_.*"]
    if sys.platform != "darwin":
        foreign.append(r"hal/[^/]+/src/platform/macos/.*")
    database = ROOT / "target/clangd"
    fragments = [
        {"CompileFlags": {"CompilationDatabase": str(database)}},
        {"If": {"PathMatch": r".*\.h", "PathExclude": r"hal/[^/]+/src/platform/macos/.*"},
         "CompileFlags": {"Add": ["-xc"]}},
        {"If": {"PathMatch": foreign, "PathExclude": configured_paths},
         "Diagnostics": {"Suppress": ["*"]}, "Index": {"Background": "Skip"}},
    ]
    database.mkdir(parents=True, exist_ok=True)
    (database / "compile_commands.json").write_text(json.dumps(entries, indent=2) + "\n")
    (ROOT / ".clangd").write_text(
        "# Generated by tools/setup-clangd.py; machine-local, do not commit.\n"
        + "\n---\n".join(json.dumps(fragment, indent=2) for fragment in fragments) + "\n"
    )
    print(f"Configured {len(entries)} compile commands in {database}")
    print("Diagnostics are quiet for unavailable platform sources; see docs/editor-setup.md.")


if __name__ == "__main__":
    main()
